#!/usr/bin/env python3
"""build_dsp.py - assemble plugin/dsp.cmajor for RE-BODY (stdlib only).

Cmajor has no imports, so the DSP lives in numbered parts under src/dsp/ and the
concatenation (filename order) is the single compilation unit that the manifest
points at (plugin/RE_BODY.cmajorpatch -> "source": "dsp.cmajor").

Before concatenating, three regions are regenerated from plugin/spec.json (the
single source of truth for parameters and endpoints), so the endpoint block, the
host-value tables and the handlers can never drift from the UI and the docs:

  src/dsp/90_main.cmajor   // BEGIN ENDPOINTS ... // END ENDPOINTS
                           stream pair + 73 `input event float paramN [[ ... ]]`
                           + the 10 `output event` endpoints, in spec order
  src/dsp/90_main.cmajor   // BEGIN HANDLERS  ... // END HANDLERS
                           paramTarget[73] (initialised to the annotated init) and
                           73 NaN/Inf-guarded `event paramN` handlers (targets only)
  src/dsp/00_header.cmajor // BEGIN PARAMS TABLE ... // END PARAMS TABLE
                           namespace rebody::params: min/max/init/step tables,
                           line-slot -> param index map, named slot/global indices

The body tables (src/dsp/10_tables.cmajor, written by tools/bodytab.py) exist in three
emission forms (docs/dev/01_TABLE_EMISSION.md); the form is read from that file's header
("emission form: namespace|main|external") and the processor side is wired automatically:

  namespace  nothing to wire (consumers read rebody::tables::<name> directly)  [recommended]
  main       90_main gets `rebody::tables::Tables tables;` and `rebody::tables::load (tables);`
             at the start of main() (regions TABLES MEMBER / TABLES LOAD)
  external   the manifest gets the "externals" object from plugin/tables.externals.json
             (bodytab.py --emit external --externals-json plugin/tables.externals.json);
             for the other forms a stale "externals" key is removed from the manifest

Usage (from anywhere; paths are resolved from this file):
    python3 tools/build_dsp.py            regenerate regions, write plugin/dsp.cmajor
    python3 tools/build_dsp.py --check    exit 1 if regions or dsp.cmajor are stale

Fails loudly (exit 1, message on stderr) on missing parts, on a spec that does not
fit the generator's assumptions, and on header constants that disagree with the spec.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "plugin" / "spec.json"
SRC = ROOT / "src" / "dsp"
OUT = ROOT / "plugin" / "dsp.cmajor"

# Parts the DSP worker owns: all must exist. 10_tables.cmajor is generated by the
# recipe worker (tools/bodytab.py); the P1 skeleton does not consume it yet, so it
# is optional here and simply joins the concatenation in filename order if present.
REQUIRED_PARTS = [
    "00_header.cmajor",
    "20_analysis.cmajor",
    "30_strikers.cmajor",
    "40_modal.cmajor",
    "50_line.cmajor",
    "90_main.cmajor",
]
OPTIONAL_PARTS = ["10_tables.cmajor"]

ENDPOINTS_BEGIN = "// BEGIN ENDPOINTS (generated from plugin/spec.json)"
ENDPOINTS_END = "// END ENDPOINTS"
HANDLERS_BEGIN = "// BEGIN HANDLERS (generated from plugin/spec.json)"
HANDLERS_END = "// END HANDLERS"
TABLE_BEGIN = "// BEGIN PARAMS TABLE (generated from plugin/spec.json)"
TABLE_END = "// END PARAMS TABLE"
MEMBER_BEGIN = "// BEGIN TABLES MEMBER (set by tools/build_dsp.py from the emission form of src/dsp/10_tables.cmajor)"
MEMBER_END = "// END TABLES MEMBER"
LOAD_BEGIN = "// BEGIN TABLES LOAD (set by tools/build_dsp.py from the emission form of src/dsp/10_tables.cmajor)"
LOAD_END = "// END TABLES LOAD"
MANIFEST = ROOT / "plugin" / "RE_BODY.cmajorpatch"
EXTERNALS_JSON = ROOT / "plugin" / "tables.externals.json"

BANNER = (
    "// GENERATED by tools/build_dsp.py from src/dsp/*.cmajor (filename order). "
    "Do not edit; edit the parts.\n"
)


class BuildError(Exception):
    pass


# --------------------------------------------------------------------------- spec

def load_spec() -> dict:
    try:
        return json.loads(SPEC.read_text(encoding="utf-8"))
    except FileNotFoundError:
        raise BuildError(f"missing {SPEC}")
    except json.JSONDecodeError as e:
        raise BuildError(f"{SPEC} is not valid JSON: {e}")


def ascii_only(what: str, s: str) -> str:
    if not s.isascii() or '"' in s or "\\" in s or "\n" in s:
        raise BuildError(f"{what} must be plain ASCII without quotes/backslashes: {s!r}")
    return s


def num(x: float) -> str:
    """Plain decimal literal without exponent, always with a decimal point."""
    s = format(float(x), ".10g")
    if "e" in s or "E" in s or "inf" in s or "nan" in s:
        raise BuildError(f"number {x!r} needs an exponent; extend num() deliberately")
    if "." not in s:
        s += ".0"
    return s


def fnum(x: float) -> str:
    return num(x) + "f"


def validate_spec(spec: dict) -> dict:
    """Check the assumptions the generator and the DSP rely on; return derived data."""
    params = spec["params"]
    if len(params) != 73:
        raise BuildError(f"expected 73 parameters, spec has {len(params)}")
    for i, p in enumerate(params):
        if p["id"] != f"param{i + 1}":
            raise BuildError(f"param ids must be sequential in order: slot {i} is {p['id']}")
        ascii_only(f"{p['id']}.name", p["name"])
        ascii_only(f"{p['id']}.unit", p.get("unit", ""))
        ascii_only(f"{p['id']}.text", p.get("text", ""))
        if not (p["min"] <= p["init"] <= p["max"]) or p["min"] >= p["max"]:
            raise BuildError(f"{p['id']}: need min < max and min <= init <= max")
        if p.get("text") and p["step"] != 1:
            raise BuildError(f"{p['id']}: enum parameters must use step 1")

    block = spec["blockOrder"]
    if len(block) != 23:
        raise BuildError(f"blockOrder must have 23 entries, has {len(block)}")
    by_id = {p["id"]: p for p in params}
    line_index: list[int] = []
    for letter in ("A", "B", "C"):
        ids = spec["lines"][letter]
        if len(ids) != 23:
            raise BuildError(f"line {letter}: expected 23 parameters, has {len(ids)}")
        for slot, pid in enumerate(ids):
            p = by_id[pid]
            if p["key"] != block[slot] or p["line"] != letter:
                raise BuildError(f"{pid}: line {letter} slot {slot} must be key {block[slot]!r}")
            line_index.append(int(pid[5:]) - 1)
    # Each slot must have identical range/step on all three lines (init may differ),
    # because the DSP clamps and quantises per slot, not per line.
    for slot in range(23):
        ref = by_id[spec["lines"]["A"][slot]]
        for letter in ("B", "C"):
            p = by_id[spec["lines"][letter][slot]]
            for k in ("min", "max", "step", "text", "unit"):
                if p.get(k) != ref.get(k):
                    raise BuildError(f"{p['id']} {k} differs from {ref['id']} (slot {slot})")
    globals_ = {}
    for pid in spec["lines"]["G"]:
        p = by_id[pid]
        globals_[p["key"]] = int(pid[5:]) - 1
    if sorted(globals_) != ["Bypass", "LowCut", "Mix", "Width"]:
        raise BuildError(f"unexpected global parameters: {sorted(globals_)}")
    if len(spec["outputs"]) != 10:
        raise BuildError(f"expected 10 output events, spec has {len(spec['outputs'])}")
    for o in spec["outputs"]:
        if not re.fullmatch(r"float(<\d+>)?", o["type"]) or not re.fullmatch(r"[A-Za-z][A-Za-z0-9]*", o["id"]):
            raise BuildError(f"unsupported output endpoint {o}")
    return {"line_index": line_index, "globals": globals_, "block": block}


# ------------------------------------------------------------------ region builders

def build_endpoints(spec: dict) -> str:
    out = [
        "input stream float<2> in;",
        "output stream float<2> out;",
    ]
    for p in spec["params"]:
        ann = [
            f'name: "{p["name"]}"',
            f"min: {num(p['min'])}",
            f"max: {num(p['max'])}",
            f"init: {num(p['init'])}",
            f"step: {num(p['step'])}",
        ]
        if p.get("unit"):
            ann.append(f'unit: "{p["unit"]}"')
        if p.get("text"):
            ann.append(f'text: "{p["text"]}"')
        out.append(f"input event float {p['id']} [[ {', '.join(ann)} ]];")
    for o in spec["outputs"]:
        out.append(f"output event {o['type']} {o['id']};")
    return "\n".join(out)


def build_handlers(spec: dict) -> str:
    params = spec["params"]
    out = [
        "// Host values in physical units, clamped to the annotated range. Handlers only set",
        "// targets (BODY:120-124 idiom, NaN/Inf-guarded); smoothing and conversion happen in main().",
        "// Enum parameters (those with text:) are rounded to the nearest step.",
        "float[73] paramTarget = (",
    ]
    inits = [fnum(p["init"]) for p in params]
    for i in range(0, 73, 6):
        chunk = ", ".join(inits[i:i + 6])
        out.append(f"    {chunk}{',' if i + 6 < 73 else ''}")
    out.append(");")
    for i, p in enumerate(params):
        value = "float(floor(v + 0.5f))" if p.get("text") else "v"
        out.append(
            f"event {p['id']} (float v) {{ if (!isnan(v) && !isinf(v)) paramTarget.at({i}) = "
            f"clamp({value}, rebody::params::minValue.at({i}), rebody::params::maxValue.at({i})); }}"
            f" // {p['name']}"
        )
    return "\n".join(out)


def build_table(spec: dict, derived: dict) -> str:
    params = spec["params"]

    def array(ctype: str, name: str, values: list[str], per_row: int) -> list[str]:
        rows = [f"    const {ctype}[{len(values)}] {name} = ("]
        for i in range(0, len(values), per_row):
            tail = "," if i + per_row < len(values) else ""
            rows.append("        " + ", ".join(values[i:i + per_row]) + tail)
        rows.append("    );")
        return rows

    out = [
        "// Zero-based indices below: parameter paramN has index N - 1.",
        "namespace rebody::params",
        "{",
        f"    const int count = {len(params)};",
        "    const int lineSlots = 23;",
    ]
    out += array("float", "minValue", [fnum(p["min"]) for p in params], 8)
    out += array("float", "maxValue", [fnum(p["max"]) for p in params], 8)
    out += array("float", "initValue", [fnum(p["init"]) for p in params], 8)
    out += array("float", "stepValue", [fnum(p["step"]) for p in params], 8)
    out.append("    // lineParam[line * 23 + slot] = parameter index of that line's block entry.")
    out += array("int", "lineParam", [str(i) for i in derived["line_index"]], 12)
    out.append("    // Global parameter indices.")
    for key in ("Mix", "Bypass", "Width", "LowCut"):
        out.append(f"    const int global{key} = {derived['globals'][key]};")
    out.append("    // Slot numbers inside a line block (spec.json blockOrder).")
    for slot, key in enumerate(derived["block"]):
        out.append(f"    const int slot{key} = {slot};")
    out.append("}")
    return "\n".join(out)


# ------------------------------------------------------------------ file handling

def replace_region(text: str, begin: str, end: str, body: str, fname: str) -> str:
    """Replace the lines strictly between the begin/end marker lines, keeping indentation."""
    lines = text.split("\n")
    idx_b = [i for i, l in enumerate(lines) if l.strip() == begin]
    idx_e = [i for i, l in enumerate(lines) if l.strip() == end]
    if len(idx_b) != 1 or len(idx_e) != 1 or idx_b[0] >= idx_e[0]:
        raise BuildError(f"{fname}: need exactly one '{begin}' followed by one '{end}'")
    indent = re.match(r"\s*", lines[idx_b[0]]).group(0)
    new = [(indent + l) if l else l for l in body.split("\n")]
    return "\n".join(lines[: idx_b[0] + 1] + new + lines[idx_e[0]:])


def check_header_constants(header: str, spec: dict) -> None:
    """The hand-written constants in 00_header must agree with the spec."""
    consts = {m.group(1): int(m.group(2)) for m in re.finditer(r"const\s+int\s+(\w+)\s*=\s*(\d+)\s*;", header)}
    want = {"numLines": 3, "numBodies": len(spec["anchors"]), "gridPoles": 96,
            "featureStride": 8, "followStride": 10}
    for k, v in want.items():
        if consts.get(k) != v:
            raise BuildError(f"00_header.cmajor: const int {k} must be {v}, found {consts.get(k)}")


def table_form() -> str:
    """Emission form of src/dsp/10_tables.cmajor: namespace | main | external | none (file absent)."""
    path = SRC / "10_tables.cmajor"
    if not path.is_file():
        return "none"
    head = "\n".join(path.read_text(encoding="utf-8").split("\n")[:12])
    m = re.search(r"emission form:\s*(namespace|main|external)\b", head)
    if not m:
        raise BuildError("10_tables.cmajor: header lacks 'emission form: namespace|main|external'")
    return m.group(1)


def apply_table_hooks(main_src: str, form: str, fname: str) -> str:
    if form == "main":
        member = "rebody::tables::Tables tables;     // body tables, filled once by load() at the start of main()"
        load = "rebody::tables::load (tables);"
    else:
        what = {"none": "no 10_tables.cmajor yet", "namespace": "namespace form, constants are read as rebody::tables::<name>",
                "external": "external form, values come from the manifest 'externals'"}[form]
        member = f"// tables: {what}"
        load = f"// tables: {what}"
    out = replace_region(main_src, MEMBER_BEGIN, MEMBER_END, member, fname)
    return replace_region(out, LOAD_BEGIN, LOAD_END, load, fname)


def manifest_text(form: str) -> str:
    """The manifest with the 'externals' object present for the external form and absent otherwise."""
    man = json.loads(MANIFEST.read_text(encoding="utf-8"))
    man.pop("externals", None)
    if form == "external":
        if not EXTERNALS_JSON.is_file():
            raise BuildError("external form: plugin/tables.externals.json missing "
                             "(python3 tools/bodytab.py --emit external --externals-json plugin/tables.externals.json)")
        ext = json.loads(EXTERNALS_JSON.read_text(encoding="utf-8"))
        man["externals"] = ext.get("externals", ext)
    return json.dumps(man, ensure_ascii=False, indent=2) + "\n"


def gather_parts() -> list[Path]:
    missing = [n for n in REQUIRED_PARTS if not (SRC / n).is_file()]
    if missing:
        raise BuildError("missing DSP parts in src/dsp: " + ", ".join(missing))
    names = sorted(p.name for p in SRC.glob("*.cmajor"))
    bad = [n for n in names if not re.fullmatch(r"\d\d_[A-Za-z0-9_]+\.cmajor", n)]
    if bad:
        raise BuildError("part names must look like NN_name.cmajor: " + ", ".join(bad))
    return [SRC / n for n in names]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="verify only; exit 1 if anything is stale")
    args = ap.parse_args()
    try:
        spec = load_spec()
        derived = validate_spec(spec)
        parts = gather_parts()

        header_path, main_path = SRC / "00_header.cmajor", SRC / "90_main.cmajor"
        header = header_path.read_text(encoding="utf-8")
        check_header_constants(header, spec)
        new_header = replace_region(header, TABLE_BEGIN, TABLE_END, build_table(spec, derived), header_path.name)
        main_src = main_path.read_text(encoding="utf-8")
        new_main = replace_region(main_src, ENDPOINTS_BEGIN, ENDPOINTS_END, build_endpoints(spec), main_path.name)
        new_main = replace_region(new_main, HANDLERS_BEGIN, HANDLERS_END, build_handlers(spec), main_path.name)
        form = table_form()
        new_main = apply_table_hooks(new_main, form, main_path.name)
        man_old = MANIFEST.read_text(encoding="utf-8")
        man_new = manifest_text(form)

        stale = []
        for path, old, new in ((header_path, header, new_header), (main_path, main_src, new_main),
                               (MANIFEST, man_old, man_new)):
            if new != old:
                stale.append(path.name)
                if not args.check:
                    path.write_text(new, encoding="utf-8")

        chunks = [BANNER]
        for p in parts:
            if p == header_path:
                text = new_header
            elif p == main_path:
                text = new_main
            else:
                text = p.read_text(encoding="utf-8")
            if not text.endswith("\n"):
                text += "\n"
            chunks.append(f"\n// ===== {p.name} =====\n{text}")
        built = "".join(chunks)

        if args.check:
            current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
            if stale or current != built:
                print("stale: " + (", ".join(stale) if stale else "plugin/dsp.cmajor"), file=sys.stderr)
                return 1
            print("ok: regions and plugin/dsp.cmajor are up to date")
            return 0

        OUT.write_text(built, encoding="utf-8")
        regen = (" (regenerated regions in: " + ", ".join(stale) + ")") if stale else ""
        print(f"wrote {OUT.relative_to(ROOT)}: {len(parts)} parts, {built.count(chr(10))} lines, tables form: {form}{regen}")
        optional_missing = [n for n in OPTIONAL_PARTS if not (SRC / n).is_file()]
        if optional_missing:
            print("note: optional part(s) not present yet: " + ", ".join(optional_missing))
        return 0
    except BuildError as e:
        print(f"build_dsp.py: {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
