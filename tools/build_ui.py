#!/usr/bin/env python3
"""build_ui.py - concatenate src/ui/*.js (filename order) into plugin/index.js.

Stdlib only; run from the repo root:  python3 tools/build_ui.py [--check]

What it guarantees (and fails loudly on):
  * every required part exists (00_header ... 90_export);
  * the generated block between `// BEGIN PARAMS (generated)` and `// END PARAMS`
    in src/ui/00_header.js is regenerated from plugin/spec.json (73 parameters,
    anchors, outputs) and plugin/bodies.json (MODE_IDS = lineModes slot identities,
    TUNE_NOTE_MAX = Tune ceiling per body, Z_TABLE = silhouette depth per path), so the UI tables can never drift from
    the spec or the recipes; --check only compares and fails on drift instead of
    rewriting;
  * line 2 of plugin/index.js is `// WINDOW SIZE: WxH` taken from spec.json view;
  * exactly one `export default function createPatchView(patchConnection)`,
    no import statements, no shadow DOM, no resize-observer API in the output;
  * the output is a valid ES module (node --check when node is installed);
  * DECAY_BASE / DECAY_RATIO in the header are cross-checked against plugin/bodies.json (warning only).
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "ui"
OUT = ROOT / "plugin" / "index.js"
SPEC = ROOT / "plugin" / "spec.json"
BODIES = ROOT / "plugin" / "bodies.json"
REQUIRED = ["00_header.js", "10_control.js", "15_silhouettes.js", "20_field.js", "30_panel.js",
            "40_telemetry.js", "50_scaling.js", "60_motion.js", "90_export.js"]
BEGIN = "// BEGIN PARAMS (generated)"
END = "// END PARAMS"
UI_KINDS = {"dial", "small", "advanced", "physics", "slider", "segmented", "button"}
FACTORY = "export default function createPatchView(patchConnection)"


def die(msg: str) -> None:
    print(f"build_ui: ERROR: {msg}", file=sys.stderr)
    sys.exit(1)


def js(value) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def load_spec() -> dict:
    if not SPEC.exists():
        die(f"missing {SPEC}")
    spec = json.loads(SPEC.read_text(encoding="utf-8"))
    params = spec.get("params") or die("spec.json has no `params`")
    for i, p in enumerate(params, 1):
        if p["id"] != f"param{i}":
            die(f"parameter #{i} is {p['id']!r}, expected 'param{i}' (host ids are sequential)")
        if p["ui"] not in UI_KINDS:
            die(f"{p['id']}: unknown ui kind {p['ui']!r}")
        for k in ("line", "key", "name", "min", "max", "step", "init"):
            if k not in p:
                die(f"{p['id']}: missing field {k!r}")
    for key in ("anchors", "anchorLabels", "anchorLabelsLong", "outputs", "plugin"):
        if key not in spec:
            die(f"spec.json: missing {key!r}")
    n = len(spec["anchors"])
    if not (len(spec["anchorLabels"]) == len(spec["anchorLabelsLong"]) == n):
        die("anchors / anchorLabels / anchorLabelsLong differ in length")
    view = spec["plugin"].get("view") or die("spec.json plugin.view missing")
    if not (view.get("width") and view.get("height")):
        die("spec.json plugin.view needs width and height")
    return spec


def load_bodies(spec: dict) -> dict:
    """plugin/bodies.json (generated by tools/bodytab.py); the UI needs `modes` and `tuneNoteRange` of every body."""
    if not BODIES.exists():
        die(f"missing {BODIES} (run tools/bodytab.py first)")
    data = json.loads(BODIES.read_text(encoding="utf-8"))
    bodies = data.get("bodies") or die("bodies.json has no `bodies`")
    n = len(spec["anchors"])
    if len(bodies) != n:
        die(f"bodies.json has {len(bodies)} bodies, spec.json has {n} anchors")
    for i, b in enumerate(bodies):
        if b.get("index") != i:
            die(f"bodies.json body #{i} has index {b.get('index')!r} (anchor order expected)")
        if len(b.get("modes", [])) != 16:
            die(f"bodies.json {b.get('name')!r}: `modes` must have 16 slots (padded layout), has {len(b.get('modes', []))}")
        z = data.get("zTable", [])[i] if i < len(data.get("zTable", [])) else None
        if not (isinstance(z, list) and len(z) == 10 and all(isinstance(v, (int, float)) for v in z)):
            die(f"bodies.json zTable[{i}] must be 10 numbers (one z per silhouette path), got {z!r}")
        rng = b.get("tuneNoteRange")
        if not (isinstance(rng, list) and len(rng) == 2 and rng[0] == 36):
            die(f"bodies.json {b.get('name')!r}: tuneNoteRange must be [36, top], got {rng!r}")
    return data


def mode_ids(bodies: dict) -> list:
    """16 slot identities per body: 0 = unused slot, ["f", Hz, label] feature mode, ["r", ratio, label] following mode."""
    rows = []
    for b in bodies["bodies"]:
        row = []
        for m in b["modes"]:
            if m is None:
                row.append(0)
            elif m["kind"] == "feature":
                row.append(["f", m["hz"], m["label"]])
            elif m["kind"] == "following":
                row.append(["r", m["ratio"], m["label"]])
            else:
                die(f"bodies.json {b['name']!r}: unknown mode kind {m['kind']!r}")
        rows.append(row)
    return rows


def params_block(spec: dict, bodies: dict) -> str:
    rows = []
    for p in spec["params"]:
        row = [p["id"], p["line"], p["key"], p["name"], p["min"], p["max"], p["step"],
               p["init"], p.get("unit", ""), p.get("text", ""), p["ui"]]
        rows.append("  " + js(row))
    lines = [
        BEGIN,
        f"// Source: plugin/spec.json ({len(spec['params'])} parameters) and plugin/bodies.json. Regenerated by tools/build_ui.py; do not edit by hand.",
        "// row = [id, line, key, name, min, max, step, init, unit, text, ui]",
        "const PARAMS = [",
        ",\n".join(rows),
        "].map(([id, line, key, name, min, max, step, init, unit, text, ui]) => ({ id, line, key, name, min, max, step, init, unit, text, ui }));",
        f"const ANCHOR_NAMES = {js(spec['anchorLabelsLong'])};",
        f"const ANCHOR_LABELS = {js(spec['anchorLabels'])};",
        f"const OUTPUTS = {js([o['id'] for o in spec['outputs']])};",
        "// Source: plugin/bodies.json (generator bodytab). TUNE_NOTE_MAX = top MIDI note of each body's Tune range (Timpani stops at C4).",
        f"const TUNE_NOTE_MAX = {js([b['tuneNoteRange'][1] for b in bodies['bodies']])};",
        "// Z_TABLE = z in px per silhouette path (10 per body, anchor order; negative = back), bodies.json `zTable` = 22_BODIES.md \"Depth\"; read by 15_silhouettes.js.",
        f"const Z_TABLE = {js(bodies['zTable'])};",
        "// MODE_IDS = identity of the 16 lineModes slots per body (anchor order): 0 = unused slot, [\"f\", Hz, label] = feature mode, [\"r\", ratio, label] = following mode.",
        "const MODE_IDS = [",
        ",\n".join("  " + js(row) for row in mode_ids(bodies)),
        "];",
        END,
    ]
    return "\n".join(lines)


def patch_header(text: str, block: str) -> str:
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        die(f"src/ui/00_header.js needs exactly one `{BEGIN}` and one `{END}` marker")
    a = text.index(BEGIN)
    b = text.index(END) + len(END)
    if b < a:
        die("PARAMS markers in the wrong order")
    return text[:a] + block + text[b:]


def check_output(out: str, spec: dict) -> None:
    lines = out.split("\n")
    view = spec["plugin"]["view"]
    want = f"// WINDOW SIZE: {view['width']}x{view['height']}"
    if len(lines) < 2 or lines[1] != want:
        die(f"line 2 of the output must be `{want}` (src/ui/00_header.js owns it), got {lines[1:2]!r}")
    if out.count(FACTORY) != 1:
        die(f"expected exactly one `{FACTORY}`, found {out.count(FACTORY)}")
    for pat, why in ((r"^\s*import\b", "import statement"), (r"\battachShadow\b", "shadow DOM"),
                     (r"ResizeObserver", "resize-observer API"), (r"\brequire\s*\(", "require call")):
        m = re.search(pat, out, re.M)
        if m:
            die(f"forbidden {why} at output line {out.count(chr(10), 0, m.start()) + 1}")
    if not out.rstrip().endswith("// END_AMORPH_UI"):
        die("output must end with `// END_AMORPH_UI` (src/ui/90_export.js)")
    ids = re.findall(r'data-param="(param\d+)"', out)
    if ids:
        die("data-param ids must be generated from PARAMS, not hard-coded in a part")


def check_decay_tables(header: str, bodies: dict) -> None:
    """Warn when DECAY_BASE / DECAY_RATIO in the header drift from plugin/bodies.json (anchors 0..9; the hybrid uses constituents)."""
    try:
        bodies = bodies["bodies"]
        base = [float(x) for x in re.search(r"const DECAY_BASE = \[([^\]]*)\]", header).group(1).split(",")]
        ratio = [float(x) for x in re.search(r"const DECAY_RATIO = \[([^\]]*)\]", header).group(1).split(",")]
    except (KeyError, AttributeError, ValueError) as exc:
        print(f"build_ui: WARNING: could not cross-check decay tables ({exc!r})")
        return
    bad = [i for i in range(min(10, len(bodies)))
           if abs(bodies[i]["decay"]["base"] - base[i]) > 1e-6 or abs(bodies[i]["decay"]["ratio"] - ratio[i]) > 1e-6]
    if bad:
        print(f"build_ui: WARNING: DECAY_BASE/DECAY_RATIO in src/ui/00_header.js differ from plugin/bodies.json at anchors {bad}; "
              "Decay seconds shown by the UI will not match the recipes")
    else:
        print("build_ui: decay tables match plugin/bodies.json (anchors 0-9)")


def node_check(out: str) -> str:
    node = shutil.which("node")
    if not node:
        return "node not found, syntax check skipped"
    with tempfile.TemporaryDirectory() as tmp:
        f = Path(tmp) / "index.mjs"
        f.write_text(out, encoding="utf-8")
        r = subprocess.run([node, "--check", str(f)], capture_output=True, text=True)
    if r.returncode != 0:
        die("node --check failed:\n" + r.stderr)
    return "node --check ok"


def main() -> int:
    ap = argparse.ArgumentParser(description="Build plugin/index.js from src/ui/*.js")
    ap.add_argument("--check", action="store_true",
                    help="verify only: fail when the PARAMS block or plugin/index.js is stale; write nothing")
    args = ap.parse_args()

    spec = load_spec()
    bodies = load_bodies(spec)
    missing = [n for n in REQUIRED if not (SRC / n).is_file()]
    if missing:
        die("missing part(s): " + ", ".join(missing))
    extra = sorted(p.name for p in SRC.glob("*.js") if p.name not in REQUIRED)
    if extra:
        print("build_ui: note: extra part(s) included in filename order: " + ", ".join(extra))

    header_path = SRC / "00_header.js"
    header = header_path.read_text(encoding="utf-8")
    block = params_block(spec, bodies)
    new_header = patch_header(header, block)
    if new_header != header:
        if args.check:
            die("generated block in src/ui/00_header.js is stale (spec.json or bodies.json changed); run python3 tools/build_ui.py")
        header_path.write_text(new_header, encoding="utf-8")
        print("build_ui: generated block (PARAMS, MODE_IDS, TUNE_NOTE_MAX, Z_TABLE) regenerated from spec.json and bodies.json")

    parts = []
    for path in sorted(SRC.glob("*.js")):
        text = new_header if path.name == "00_header.js" else path.read_text(encoding="utf-8")
        parts.append(text if text.endswith("\n") else text + "\n")
    out = "".join(parts)
    check_output(out, spec)
    status = node_check(out)
    check_decay_tables(new_header, bodies)

    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != out:
            die("plugin/index.js is stale; run python3 tools/build_ui.py")
        print(f"build_ui: up to date ({status})")
        return 0
    OUT.write_text(out, encoding="utf-8")
    n = len(spec["params"])
    print(f"build_ui: wrote {OUT.relative_to(ROOT)} ({len(parts)} parts, {out.count(chr(10))} lines, "
          f"{len(out.encode('utf-8'))} bytes, {n} parameters, {status})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
