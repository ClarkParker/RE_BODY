// Morph position (0..NUM_ANCHORS-1) -> weight per anchor. The last segment (Sax -> Obosaxolele) is an equal blend of
// Oboe, Sax and Ukulele, exactly the original's rule (index.js:9-20) moved to the 11-anchor order.
const morphWeights = value => {
    const top = NUM_ANCHORS - 1, position = clamp(value, 0, top), weights = Array(NUM_ANCHORS).fill(0);
    if (position >= top - 1) {
        const t = position - (top - 1);
        weights[A_OBOE] = t / 3; weights[A_UKE] = t / 3; weights[A_SAX] = 1 - 2 * t / 3;
        return weights;
    }
    const a = Math.floor(position), b = Math.min(top, a + 1), t = position - a;
    weights[a] += 1 - t; weights[b] += t;
    return weights;
};
const decayMapping = weights => {
    const hybrid = weights[A_OBOE] > 0 && weights[A_UKE] > 0 ? clamp(3 * Math.min(weights[A_OBOE], weights[A_UKE]), 0, 1) : 0;
    const aftermath = hybrid * hybrid * (3 - 2 * hybrid);
    return {
        base: Math.exp(weights.reduce((s, w, i) => s + w * Math.log(DECAY_BASE[i]), 0)) * Math.max(1, .30 + 2.20 * aftermath),
        logRatio: weights.reduce((s, w, i) => s + w * Math.log(DECAY_RATIO[i]), 0)
    };
};
