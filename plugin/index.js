const fxFlow = (x, y, t) => (Math.sin(x * .011 + t * .23) + Math.sin(y * .017 - t * .19) + Math.sin((x + y) * .007 + t * .11)) / 3 * Math.PI * 1.5;   // slow flow-field angle

