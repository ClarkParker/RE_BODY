        if (key === "Enable") this.refreshTabs();
        else if (key === "Morph") this.refreshMorph(line);
        else if (line === this.activeLine && key === "Tune") this.touchField();
        else if (line === this.activeLine && (key === "Follow" || key === "Hold")) this.refreshFollow();
